"""
actions_system.py
=================
System-level remediation actions for SecurityWizard.

All build_plan functions are read-only: they inspect files and run read-only
commands, then return a plan dict.  They never raise and never modify the system.
"""

from __future__ import annotations

import os

from common import read_text, run_cmd


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _file_exists(path: str) -> bool:
    """Return True if *path* exists and is a regular file."""
    try:
        return os.path.isfile(path)
    except OSError:
        return False


def _current_mode(path: str) -> str:
    """Return the octal mode string (e.g. '0644') or 'missing'."""
    try:
        mode = os.stat(path).st_mode
        return format(mode & 0o777, "03o")
    except OSError:
        return "missing"


def _perm_plan(file_path: str, target_mode: int, title: str, description: str) -> dict:
    """Build a permission-only plan for a single file."""
    if not _file_exists(file_path):
        return {
            "file_changes": [],
            "perm_changes": [],
            "validate_commands": [],
            "commands": [],
            "inverse_commands": [],
            "warnings": [],
            "blockers": [f"{file_path} does not exist"],
        }
    return {
        "file_changes": [],
        "perm_changes": [{"path": file_path, "mode": target_mode}],
        "validate_commands": [],
        "commands": [],
        "inverse_commands": [],
        "warnings": [],
        "blockers": [],
    }


# ---------------------------------------------------------------------------
# sysctl_baseline
# ---------------------------------------------------------------------------

def _is_container_or_multihomed() -> bool:
    """
    Detect if the host requires loose rp_filter (mode 2) instead of strict (mode 1).
    True if:
    - Docker is present (/var/lib/docker or docker binary)
    - Kubernetes is present (/etc/kubernetes or kubelet)
    - WireGuard is present (/etc/wireguard or wg binary)
    - Multiple default routes or >1 non-loopback interface with a gateway
    """
    # 1. Docker
    if os.path.isdir("/var/lib/docker"):
        return True
    rc, _, _ = run_cmd(["which", "docker"])
    if rc == 0:
        return True

    # 2. Kubernetes
    if os.path.isdir("/etc/kubernetes"):
        return True
    rc, _, _ = run_cmd(["which", "kubelet"])
    if rc == 0:
        return True

    # 3. WireGuard
    if os.path.isdir("/etc/wireguard"):
        return True
    rc, _, _ = run_cmd(["which", "wg"])
    if rc == 0:
        return True

    # 4. Multi-homed / Multiple default routes
    rc, out, _ = run_cmd(["ip", "route", "show", "default"])
    if rc == 0:
        lines = [l for l in out.strip().splitlines() if l.strip()]
        if len(lines) > 1:
            return True

    # 5. >1 non-loopback interface with a gateway
    rc, out, _ = run_cmd(["ip", "-o", "-4", "route", "show"])
    if rc == 0:
        gateways = set()
        for line in out.strip().splitlines():
            if "via" in line:
                parts = line.split()
                if len(parts) > 1:
                    gateways.add(parts[1])
        if len(gateways) > 1:
            return True

    return False


def _get_sysctl_content() -> str:
    """Generate sysctl content with appropriate rp_filter value."""
    if _is_container_or_multihomed():
        rp_filter = "2"
        comment = "# Loose mode (2) for containerized/multi-homed hosts"
    else:
        rp_filter = "1"
        comment = "# Strict mode (1) for single-homed hosts"
    return f"""\
# /etc/sysctl.d/99-securitywizard.conf
# Generated by SecurityWizard - sysctl_baseline
{comment}
net.ipv4.conf.all.rp_filter={rp_filter}
net.ipv4.conf.default.rp_filter={rp_filter}
net.ipv4.conf.all.accept_redirects=0
net.ipv4.conf.default.accept_redirects=0
net.ipv6.conf.all.accept_redirects=0
net.ipv6.conf.default.accept_redirects=0
net.ipv4.conf.all.send_redirects=0
net.ipv4.tcp_syncookies=1
net.ipv4.conf.all.accept_source_route=0
kernel.dmesg_restrict=1
kernel.kptr_restrict=2
"""


def _build_sysctl_baseline() -> dict:
    try:
        content = _get_sysctl_content()
        warnings = []
        if _is_container_or_multihomed():
            warnings.append("Using loose rp_filter (2) because Docker/Kubernetes/WireGuard/multi-homed environment detected.")
        return {
            "file_changes": [{"path": "/etc/sysctl.d/99-securitywizard.conf", "new_content": content}],
            "perm_changes": [],
            "validate_commands": [],
            "commands": [["sysctl", "--system"]],
            "inverse_commands": [["sysctl", "--system"]],
            "warnings": warnings,
            "blockers": [],
        }
    except Exception:
        return {
            "file_changes": [],
            "perm_changes": [],
            "validate_commands": [],
            "commands": [],
            "inverse_commands": [],
            "warnings": [],
            "blockers": ["Unexpected error building sysctl plan"],
        }


